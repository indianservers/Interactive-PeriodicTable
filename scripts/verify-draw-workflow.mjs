import assert from 'node:assert/strict';
import initRDKit from '@rdkit/rdkit';
import { parseMolfile,structureMolfile,emptyStructure,addRing } from '../src/utils/structureDrawing.js';
import { placeGroup,attachRing,fuseRing } from '../src/utils/drawTemplates.js';
import { documentStamp,reorderDocument,duplicateDrawing } from '../src/utils/drawDocuments.js';
import { mappedMolfile,reactionRxn,reactionSmiles,importReaction,reactionSchemeSvg } from '../src/utils/drawReactionFormats.js';
import { validateDrawWorkspace } from '../src/utils/drawWorkspace.js';
import { analyzeReactionMolecule } from '../src/utils/drawReaction.js';
const rd=await initRDKit();
function drawing(smiles){const mol=rd.get_mol(smiles);assert.ok(mol);mol.set_new_coords();const model=parseMolfile(mol.get_molblock());mol.delete();return model;}
function smiles(model){const mol=rd.get_mol(structureMolfile(model));assert.ok(mol,'graph must validate');const result=mol.get_smiles();mol.delete();return result;}
const ethane=drawing('CC');
assert.equal(smiles(placeGroup(ethane,'Me',1)),'CCC');
assert.equal(smiles(placeGroup(emptyStructure(),'Et',null)),'CC');
assert.equal(smiles(placeGroup(emptyStructure(),'Ph',null)),'c1ccccc1');
assert.equal(smiles(placeGroup(ethane,'COOH',1)),'CCC(=O)O');
assert.equal(analyzeReactionMolecule(rd,attachRing(ethane,1)).formula,'C8H16');
const cyclo=drawing('C1CCCCC1');
assert.equal(analyzeReactionMolecule(rd,fuseRing(cyclo,0)).formula,'C10H18');
const benzene=drawing('c1ccccc1');
for(const side of ['auto','left','right'])assert.equal(analyzeReactionMolecule(rd,fuseRing(benzene,0,6,true,side)).formula,'C10H8');
assert.equal(fuseRing(cyclo,0).bonds.length,11);
assert.throws(()=>fuseRing(drawing('C#C'),0));
assert.throws(()=>placeGroup(ethane,'Bogus',1));
const doc={id:1,title:'Original',name:'Ethanol',model:drawing('CCO'),sdfText:''};
const copy=duplicateDrawing(doc,2);assert.equal(smiles(copy.model),'CCO');copy.model.atoms[0].x+=20;assert.notEqual(copy.model.atoms[0].x,doc.model.atoms[0].x);
assert.notEqual(documentStamp(doc),documentStamp({...doc,title:'Renamed'}));
assert.notEqual(documentStamp(doc),documentStamp({...doc,model:copy.model}));
assert.equal(documentStamp(doc),documentStamp(structuredClone(doc)));
assert.deepEqual(reorderDocument([doc,copy],2,-1).map(d=>d.id),[2,1]);
assert.deepEqual(reorderDocument([doc,copy],1,-1).map(d=>d.id),[1,2]);
const imported=importReaction(rd,'[CH3:7][OH:8]>[Na+]>[CH2:7]=[O:8]');
assert.deepEqual(imported.components.map(c=>c.role),['reactant','agent','product']);
assert.deepEqual(imported.components[0].maps,{1:7,2:8});
const docs=imported.components.map((c,i)=>({id:i+1,title:`Component ${i+1}`,name:c.name,model:c.model}));
const reaction={conditions:'Heat < 80 °C & catalyst',arrow:'equilibrium',participants:imported.components.map((c,i)=>({id:i+1,documentId:i+1,role:c.role,coefficient:1,amount:'',unit:'g',maps:c.maps}))};
const rxn=reactionRxn(reaction,docs),rsmi=reactionSmiles(rd,reaction,docs);
const rdRxn=rd.get_rxn(rxn);assert.ok(rdRxn,'RXN is recognized by RDKit');rdRxn.delete();
const fromRxn=importReaction(rd,rxn);assert.equal(fromRxn.conditions,reaction.conditions);assert.equal(fromRxn.components.length,3);
assert.deepEqual(fromRxn.components[0].maps,{1:7,2:8});
const fromSmiles=importReaction(rd,rsmi);assert.equal(fromSmiles.components.length,3);assert.deepEqual(Object.values(fromSmiles.components[0].maps).sort(),[7,8]);
assert.ok(rsmi.includes(':7')&&rsmi.includes(':8'));
const svg=reactionSchemeSvg(rd,reaction,docs);assert.ok(svg.startsWith('<svg'));assert.ok(svg.includes('&lt;')&&svg.includes('&amp;'));assert.ok(!svg.includes('Heat < 80'));
// External RXN files commonly have an empty first MOL title line.
const blankTitleRxn=rxn.replaceAll('$MOL\nChemistry Structure\n','$MOL\n\n');assert.equal(importReaction(rd,blankTitleRxn).components.length,3);
for(const value of ['CCO','CCO>>','CCO>>>CC=O','$RXN\ninvalid'])assert.throws(()=>importReaction(rd,value));
assert.throws(()=>importReaction(rd,'x'.repeat(2000001)));
const chiral=importReaction(rd,'[CH3:1][C@H:2]([OH:3])C(=O)O>>[CH3:1][C@H:2]([OH:3])C(=O)O');assert.equal(chiral.components[0].maps[2],2);
assert.equal(smiles(chiral.components[0].model),smiles(chiral.components[1].model));
const savedDocuments={1:documentStamp(doc)};
const workspace=validateDrawWorkspace({version:1,activeDocumentId:1,documents:[doc],savedDocuments});assert.deepEqual(workspace.savedDocuments,savedDocuments);
console.log('PASS: group attachment, ring attachment and fusion; isolated duplicates, document stamps and ordering; RXN/reaction SMILES atom maps, agents and chirality; full-scheme SVG and backward-compatible workspace persistence.');

assert.throws(()=>mappedMolfile(doc.model,{999:1}),/deleted atom/);
const unknownStereo=importReaction(rd,'FC=CF>>FC=CF');
const unknownDoc={...doc,model:unknownStereo.components[0].model};
assert.ok(validateDrawWorkspace({version:1,documents:[unknownDoc],activeDocumentId:1}).documents[0].model.bonds.some(b=>b.stereo===3));
const longScheme=reactionSchemeSvg(rd,{...reaction,conditions:'Long reaction condition '.repeat(70)},docs);
assert.ok(Number(longScheme.match(/height="(\d+)"/)[1])>390);
console.log('PASS: stale map rejection, unknown double-bond stereo persistence, and long-condition scheme sizing.');
